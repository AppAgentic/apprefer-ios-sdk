#!/usr/bin/env python3
"""Builds Sources/AppRefer/Resources/<lang>.lproj/Localizable.strings from the shared
Support translation table (Localization/support-strings.json, the same file the Android,
Flutter and React Native SDKs use). Plural keys become `key#<cldr category>`.

    python3 scripts/generate-support-strings.py [path/to/support-strings.json]
"""
import json, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "Localization", "support-strings.json")
table = json.load(open(source, encoding="utf-8"))
keys = table["keys"]
languages = {"en": {k: v["en"] for k, v in keys.items()}, **table["translations"]}
out_dir = os.path.join(root, "Sources", "AppRefer", "Resources")

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

for lang, strings in sorted(languages.items()):
    lines = ["/* Generated by scripts/generate-support-strings.py from Localization/support-strings.json. Do not edit. */", ""]
    for key in keys:  # table order
        value = strings[key]
        comment = keys[key].get("comment", "").replace("*/", "* /")
        if isinstance(value, dict):
            for category, text in value.items():
                lines.append(f'/* {comment} Plural form "{category}". */')
                lines.append(f'"{esc(key)}#{category}" = "{esc(text)}";')
        else:
            lines.append(f"/* {comment} */")
            lines.append(f'"{esc(key)}" = "{esc(value)}";')
    folder = os.path.join(out_dir, f"{lang}.lproj")
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
print(f"{len(languages)} languages, {len(keys)} keys -> {out_dir}")
