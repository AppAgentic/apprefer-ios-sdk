import Foundation
import StoreKit
#if canImport(UIKit) && !os(watchOS)
import UIKit
#endif

/// Receives entitlement changes (called on the main thread).
public protocol AppReferBillingDelegate: AnyObject {
    func appReferBilling(didReceiveUpdated customerInfo: AppReferCustomerInfo)
}

/// AppRefer Billing: StoreKit 2 purchases and entitlements, verified and recorded by
/// AppRefer. A drop-in replacement for RevenueCat's `Purchases`.
///
/// ```swift
/// await AppRefer.configure(apiKey: "pk_live_...")
/// AppReferBilling.configure(entitlementsByProduct: ["pro_yearly": ["premium"]])
///
/// let products = try await AppReferBilling.products(["pro_yearly"])
/// let result = try await AppReferBilling.purchase(products[0])
/// if result.customerInfo.entitlements["premium"]?.isActive == true { unlock() }
/// ```
public enum AppReferBilling {
    public typealias CustomerInfo = AppReferCustomerInfo
    public typealias EntitlementInfo = AppReferEntitlementInfo
    public typealias RejectedPurchase = AppReferRejectedPurchase

    public enum FetchPolicy: Sendable, Equatable {
        /// The cached answer if it is under 5 minutes old, otherwise the server.
        case cachedOrFetched
        /// Always ask the server.
        case fetchCurrent
    }

    /// A signed promotional offer (signature generated by your backend).
    public struct PromotionalOffer: Sendable {
        public let offerId: String
        public let keyId: String
        public let nonce: UUID
        public let signature: Data
        public let timestamp: Int

        public init(offerId: String, keyId: String, nonce: UUID, signature: Data, timestamp: Int) {
            self.offerId = offerId
            self.keyId = keyId
            self.nonce = nonce
            self.signature = signature
            self.timestamp = timestamp
        }
    }

    public struct PurchaseResult: Sendable {
        public enum Outcome: Sendable, Equatable {
            case purchased
            case userCancelled
            /// Waiting on Ask to Buy or SCA; it arrives later through the transaction
            /// listener and `customerInfoStream`.
            case pending
        }

        public let outcome: Outcome
        /// The verified transaction, when `outcome == .purchased`.
        public let transaction: Transaction?
        public let customerInfo: AppReferCustomerInfo

        /// RevenueCat-style flag.
        public var userCancelled: Bool { outcome == .userCancelled }
    }

    // MARK: - State

    private static let lock = NSLock()
    private nonisolated(unsafe) static var _engine: BillingEngine?
    private nonisolated(unsafe) static weak var _delegate: AppReferBillingDelegate?
    private nonisolated(unsafe) static var foregroundObserver: NSObjectProtocol?
    static let broadcaster = CustomerInfoBroadcaster()

    static var engine: BillingEngine? {
        lock.lock()
        defer { lock.unlock() }
        return _engine
    }

    /// Whether `configure` has been called.
    public static var isConfigured: Bool { engine != nil }

    /// Receives every entitlement change on the main thread.
    public static var delegate: AppReferBillingDelegate? {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _delegate
        }
        set {
            lock.lock()
            _delegate = newValue
            lock.unlock()
        }
    }

    // MARK: - Configure

    /// Starts AppRefer Billing. Call once at launch, after `AppRefer.configure(apiKey:)`.
    ///
    /// - Parameters:
    ///   - apiKey: SDK key. Defaults to the key passed to `AppRefer.configure`.
    ///   - appUserId: Your user id. Nil uses an anonymous `$ARAnon:<UUID>` kept in the Keychain.
    ///   - entitlementsByProduct: productId → entitlement ids, used when AppRefer is
    ///     unreachable. Mirror the app's AppRefer billing config. Products not listed
    ///     fall back to what the server last said, then `defaultEntitlement`.
    ///   - defaultEntitlement: Entitlement for unmapped products (server default `premium`).
    public static func configure(
        apiKey: String? = nil,
        appUserId: String? = nil,
        entitlementsByProduct: [String: [String]] = [:],
        defaultEntitlement: String? = nil,
        debug: Bool = false,
        logLevel: Int = 1,
        environment: BillingEnvironment? = nil
    ) {
        let logger = AppReferLogger(debug: debug, logLevel: logLevel)
        lock.lock()
        if _engine != nil {
            lock.unlock()
            logger.warn("AppReferBilling.configure called more than once; ignoring")
            return
        }

        let explicitKey = apiKey
        let storeContext = ResolvedBillingStoreContext()
        let storeKit = LiveBillingStoreKit()
        let storage = BillingStorage.live()
        let automatic = AutomaticBillingScope(directory: storage.directory, apiKey: { explicitKey ?? AppRefer.currentApiKey() }, explicit: environment, resetEpoch: { AppRefer.accountEpoch() })
        let scope: @Sendable () -> BillingEnvironment? = {
            automatic.select(base: storeContext.select(apiKey: explicitKey ?? AppRefer.currentApiKey(), explicit: environment), verifiedStoreEnvironment: storeContext.verifiedEnvironment)
        }
        let broadcaster = self.broadcaster
        broadcaster.setValidator { info in scope().map { info.environment == $0 } ?? false }
        let engine = BillingEngine(
            api: BillingAPIClient(
                // Purchases may be forwarded as conversions only for ATT-authorized installs,
                // so they go to the tracking host only then; otherwise to the first-party host.
                // With collection off or after reset, never the tracking host.
                baseURLProvider: {
                    [AppRefer.installLinkAllowed() ? LiveTrackingStatusProvider().current().baseURL : AppReferConfig.backendURL]
                },
                apiKey: { explicitKey ?? AppRefer.currentApiKey() },
                transport: URLSessionBillingTransport(),
                environmentProvider: scope
            ),
            storage: storage,
            queue: PendingPurchaseQueue(fileURL: storage.directory.appendingPathComponent("pending_purchases.json")),
            storeKit: storeKit,
            options: .init(productEntitlements: entitlementsByProduct, defaultEntitlement: defaultEntitlement, environment: scope, automaticScope: automatic),
            appUserId: appUserId,
            // Same gate as Support: no device id while collection is off, or after
            // reset() until configure runs again.
            appreferId: { AppRefer.supportDeviceId() },
            logger: logger,
            onChange: { info in
                broadcaster.publish(info)
                DispatchQueue.main.async {
                    guard broadcaster.isValid(info) else { return }
                    AppReferBilling.delegate?.appReferBilling(didReceiveUpdated: info)
                }
            }
        )
        _engine = engine
        lock.unlock()

        DispatchQueue.main.async { Task {
            await storeContext.resolve(from: storeKit, explicit: environment)
            await engine.start()
        } }
        observeForeground(engine)
    }

    private static func observeForeground(_ engine: BillingEngine) {
        #if canImport(UIKit) && !os(watchOS)
        let observer = NotificationCenter.default.addObserver(
            forName: UIApplication.willEnterForegroundNotification, object: nil, queue: nil
        ) { _ in
            Task { await engine.refreshOfferingsIfStale() }
            Task {
                _ = await engine.customerInfo(policy: .cachedOrFetched)
                await engine.migrationSync()
                await engine.drainQueue()
            }
        }
        lock.lock()
        foregroundObserver = observer
        lock.unlock()
        #endif
    }

    /// Called by `AppRefer.reset()`: the current Billing user (if Billing ever had one) is
    /// remembered as the previous account, so it gets no install device id, device
    /// attributes or re-link, even after a relaunch, until logIn/logOut or a different user.
    static func recordAccountReset(_ snapshot: IdentitySnapshot) async {
        if let engine {
            // Configured while reset() ran: only a different appUserId is a new account; no
            // appUserId, or the same user, resumes the previous one, who is marked.
            if snapshot.engine == nil,
               configuredForAnotherUser(configured: engine.configuredAppUserId, storedAtReset: snapshot.storedUser) { return }
            // An engine configured meanwhile: every logIn/logOut on it came after reset().
            await engine.recordAccountReset(resetTicket: snapshot.engine === engine ? snapshot.ticket : 0)
        } else {
            BillingStorage.live(createDirectory: false).recordAccountReset()
        }
    }

    static func configuredForAnotherUser(configured: String?, storedAtReset: String?) -> Bool {
        guard let configured else { return false }
        return configured != storedAtReset
    }

    /// Taken synchronously when reset() is called: a logIn/logOut called after it (a later
    /// ticket) that has been applied means the marker write would land on the next account.
    struct IdentitySnapshot: @unchecked Sendable {
        let engine: BillingEngine?
        let ticket: Int
        /// Billing's stored user when no engine existed yet (to judge a configure meanwhile).
        let storedUser: String?
    }
    static func identitySnapshot() -> IdentitySnapshot {
        let engine = self.engine
        guard let engine else {
            return IdentitySnapshot(engine: nil, ticket: 0, storedUser: BillingStorage.live(createDirectory: false).storedCurrentAppUserId)
        }
        return IdentitySnapshot(engine: engine, ticket: engine.identityChanges.take(), storedUser: nil)
    }

    private static func requireEngine() throws -> BillingEngine {
        guard let engine else { throw AppReferBillingError.notConfigured }
        return engine
    }

    // MARK: - Identity

    /// The current app user id (`$ARAnon:<UUID>` while anonymous).
    public static var appUserId: String {
        get async {
            guard let engine else { return "" }
            return await engine.currentAppUserId
        }
    }

    public static var isAnonymous: Bool {
        get async {
            guard let engine else { return true }
            return await engine.isAnonymous
        }
    }

    /// Switches to a signed-in user. Purchases made while anonymous move to them.
    @discardableResult
    public static func logIn(_ appUserId: String) async throws -> AppReferCustomerInfo {
        let engine = try requireEngine()
        // Call order is fixed now; it counts against reset() only once applied (a logIn
        // that throws never cancels reset()'s marker).
        let ticket = engine.identityChanges.take()
        return try await engine.logIn(appUserId, ticket: ticket)
    }

    /// Signs out and starts a fresh anonymous id.
    @discardableResult
    public static func logOut() async throws -> AppReferCustomerInfo {
        let engine = try requireEngine()
        let ticket = engine.identityChanges.take()
        return await engine.logOut(ticket: ticket)
    }

    /// Customer attributes, sent with the next AppRefer call. Supported keys:
    /// `$email`, `$displayName`, `$phoneNumber`, `$idfa`, `$idfv`, `$fbAnonId`,
    /// `$attConsentStatus`, `$deviceVersion`, `$ip`, `$gpsAdId`. The device keys are dropped,
    /// not sent, while collection is off or after `AppRefer.reset()` until configure.
    public static func setAttributes(_ attributes: [String: String]) async {
        await engine?.setAttributes(attributes)
    }

    public static func setEmail(_ email: String) async { await setAttributes(["$email": email]) }
    public static func setDisplayName(_ name: String) async { await setAttributes(["$displayName": name]) }
    public static func setPhoneNumber(_ phone: String) async { await setAttributes(["$phoneNumber": phone]) }

    // MARK: - Entitlements

    /// The customer's entitlements. Never throws: if AppRefer can't be reached, the
    /// answer comes from StoreKit's verified current entitlements merged with the cache.
    public static func customerInfo(fetchPolicy: FetchPolicy = .cachedOrFetched) async -> AppReferCustomerInfo {
        if let engine { return await engine.customerInfo(policy: fetchPolicy) }
        // Before Billing.configure, only the registered key can select a scope.
        let transactions = await LiveBillingStoreKit().currentEntitlements()
        let key = AppRefer.currentApiKey()
        let detected = key?.hasPrefix("pk_test_") == true ? BillingEnvironment.sandbox : await LiveBillingStoreKit().storeEnvironment()
        let selected = key != nil && key == AppRefer.currentApiKey() ? detected : nil
        let local = LocalEntitlements.compute(
            transactions: transactions.filter { selected != nil && $0.environment == selected },
            configured: [:], learned: [:], defaultEntitlement: nil, now: Date()
        )
        let result = LocalEntitlements.merge(server: nil, local: local, appUserId: "", now: Date(), source: .localFallback)
        return AppReferCustomerInfo(appUserId: result.appUserId, entitlements: result.entitlements, activeSubscriptions: result.activeSubscriptions, requestDate: result.requestDate, source: result.source, environment: selected)
    }

    /// Every entitlement change, starting with the latest known value.
    public static var customerInfoStream: AsyncStream<AppReferCustomerInfo> {
        broadcaster.stream()
    }

    public static func offerings(fetchPolicy: FetchPolicy = .cachedOrFetched) async throws -> AppReferOfferings {
        try await requireEngine().offerings(policy: fetchPolicy)
    }
    public static func purchase(package: AppReferPackage) async throws -> PurchaseResult {
        try await purchase(package.storeProduct, presentedOfferingContext: package.presentedOfferingContext)
    }
    // MARK: - Products and purchases

    /// StoreKit products in the order requested.
    public static func products(_ productIds: [String]) async throws -> [Product] {
        let products = try await Product.products(for: productIds)
        return products.sorted {
            (productIds.firstIndex(of: $0.id) ?? .max) < (productIds.firstIndex(of: $1.id) ?? .max)
        }
    }

    /// Buys a product. Tags the purchase with the customer's AppRefer account token,
    /// verifies it, records it with AppRefer and finishes it. Who is buying is saved on the
    /// device before the sheet opens, so a purchase that completes later (Ask to Buy, slow
    /// payment, after a restart or user switch) still goes to them; if that can't be saved
    /// it throws `AppReferBillingError.purchaseIntentNotSaved` without opening the sheet.
    public static func purchase(
        _ product: Product,
        promotionalOffer: PromotionalOffer? = nil,
        options extraOptions: Set<Product.PurchaseOption> = [],
        presentedOfferingContext: PresentedOfferingContext? = nil
    ) async throws -> PurchaseResult {
        let engine = try requireEngine()
        var options = extraOptions
        // Whoever is signed in now owns the purchase, even if logIn/logOut runs during the sheet.
        let intent = try await engine.beginPurchase(productId: product.id, context: presentedOfferingContext)
        if let token = intent.accountToken {
            options.insert(.appAccountToken(token))
        }
        if let offer = promotionalOffer {
            options.insert(.promotionalOffer(
                offerID: offer.offerId, keyID: offer.keyId, nonce: offer.nonce,
                signature: offer.signature, timestamp: offer.timestamp
            ))
        }

        let result: Product.PurchaseResult
        do {
            result = try await product.purchase(options: options)
        } catch {
            if BillingEngine.endsPurchase(error) { await engine.endPurchase(intent) }
            throw error
        }
        switch result {
        case .success(let verification):
            let update = LiveBillingStoreKit.update(from: verification)
            guard case .verified(let transaction) = verification else {
                _ = await engine.process(update, initiator: intent.appUserId, intent: intent) // rejected list; no access
                throw AppReferBillingError.unverifiedTransaction
            }
            let info = await engine.process(update, initiator: intent.appUserId, intent: intent)
            AppRefer.conversionValueMayHaveChanged()
            return PurchaseResult(outcome: .purchased, transaction: transaction, customerInfo: info)
        case .userCancelled:
            await engine.endPurchase(intent)
            return PurchaseResult(outcome: .userCancelled, transaction: nil, customerInfo: await engine.customerInfo(policy: .cachedOrFetched))
        case .pending:
            // The intent stays: the purchase arrives later through the transaction listener.
            return PurchaseResult(outcome: .pending, transaction: nil, customerInfo: await engine.customerInfo(policy: .cachedOrFetched))
        @unknown default:
            return PurchaseResult(outcome: .pending, transaction: nil, customerInfo: await engine.customerInfo(policy: .cachedOrFetched))
        }
    }

    /// `AppStore.sync()` then sends every current entitlement to AppRefer, and again any
    /// verifiable purchase in `rejectedPurchases()` StoreKit no longer lists.
    /// Throws if the user cancels the App Store sign-in.
    @discardableResult
    public static func restorePurchases() async throws -> AppReferCustomerInfo {
        try await requireEngine().restore()
    }

    /// Purchases AppRefer refused for good (400/413/422), that StoreKit could not verify,
    /// or that could not be delivered within 50 attempts / 90 days. Each was saved here
    /// before its transaction was finished (consumables are left unfinished), for support,
    /// and `restorePurchases()` sends the verifiable ones again. Empty before configure.
    public static func rejectedPurchases() async -> [RejectedPurchase] {
        await engine?.rejectedPurchases() ?? []
    }
}

/// Fans entitlement changes out to any number of `AsyncStream` subscribers.
final class CustomerInfoBroadcaster: @unchecked Sendable {
    private let lock = NSLock()
    private var validator: @Sendable (AppReferCustomerInfo) -> Bool = { _ in true }
    func setValidator(_ value: @escaping @Sendable (AppReferCustomerInfo) -> Bool) { lock.lock(); validator = value; lock.unlock() }
    func isValid(_ info: AppReferCustomerInfo) -> Bool { lock.lock(); let check = validator; lock.unlock(); return check(info) }
    private var latest: AppReferCustomerInfo?
    private var continuations: [UUID: AsyncStream<AppReferCustomerInfo>.Continuation] = [:]

    func publish(_ info: AppReferCustomerInfo) {
        guard isValid(info) else { return }
        lock.lock()
        latest = info
        let targets = Array(continuations.values)
        lock.unlock()
        for continuation in targets where isValid(info) { continuation.yield(info) }
    }

    func stream() -> AsyncStream<AppReferCustomerInfo> {
        let buffered = AsyncStream<AppReferCustomerInfo> { continuation in
            let id = UUID()
            lock.lock()
            continuations[id] = continuation
            let current = latest
            lock.unlock()
            if let current, isValid(current) { continuation.yield(current) }
            continuation.onTermination = { [weak self] _ in
                guard let self else { return }
                self.lock.lock()
                self.continuations.removeValue(forKey: id)
                self.lock.unlock()
            }
        }
        let reader = ScopedCustomerInfoReader(buffered) { [weak self] in self?.isValid($0) == true }
        // Unfolding runs when next() is consumed, rather than when the broadcaster
        // queued the element. A key change cannot replay an old buffered grant.
        return AsyncStream(unfolding: { await reader.next() })
    }
}

/// AsyncIteratorProtocol requires serial next() calls. The stream's unfolding
/// closure owns this iterator; it never escapes to another consumer.
private final class ScopedCustomerInfoReader: @unchecked Sendable {
    private var iterator: AsyncStream<AppReferCustomerInfo>.Iterator
    private let valid: @Sendable (AppReferCustomerInfo) -> Bool
    init(_ stream: AsyncStream<AppReferCustomerInfo>, valid: @escaping @Sendable (AppReferCustomerInfo) -> Bool) {
        iterator = stream.makeAsyncIterator()
        self.valid = valid
    }
    func next() async -> AppReferCustomerInfo? {
        while let info = await iterator.next() {
            if valid(info) { return info }
        }
        return nil
    }
}
